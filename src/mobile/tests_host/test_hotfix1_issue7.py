def _snackbar(run: Run, message: str):
    """The SnackBar on screen whose text is ``message`` (None when there is none)."""
    for control in run.tester._walk():
        if type(control).__name__ == "Text" and getattr(control, "value", None) == message:
            node = control
            while node is not None and type(node).__name__ != "SnackBar":
                node = getattr(node, "parent", None)
            if node is not None:
                return node
    return None


