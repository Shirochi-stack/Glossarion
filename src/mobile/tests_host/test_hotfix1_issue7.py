            assert await _until(lambda: _buttons(book_page) == ((False, None), (False, None)), 20), \
                _buttons(book_page)
            after = log.after(glossary_id, mark_log)
            assert after and not after[-1]["run"][0] and not after[-1]["qa"][0], log.rows[mark_log:]
            assert app.shell.top_screen is book_page and book_page.chapters is chapters

            # ---- 4. Run QA scan: ONE qa_scan job in the mobile QA defaults --------------------------------
            known = {s.id for s in js.view().history}
            first_scan = scans.hold()
            # a fast double tap that reaches the app twice (before the client drew the disabled button)
            await run.session.dispatch_event(chapters.qa_button._i, "click", None)
            await run.session.dispatch_event(chapters.qa_button._i, "click", None)
            qsnap = await _until(lambda: next((s for s in [js.view().active, *js.view().queue, *js.view().history]
                                               if s is not None and s.id not in known and _kind(s) == "qa_scan"),
                                              None), 60)
            assert qsnap, f"Run QA scan started no qa_scan job: {js.view()}"
            qa_id = qsnap.id
            spec = qsnap.spec
            assert spec.params["mode"] == qm.CHAT_QA_MODE == "quick-scan"
            assert [{k: _norm(v) for k, v in t.items()} for t in spec.params["targets"]] == [
                {"folder": _norm(workspace), "source": _norm(raw)}]
            assert not spec.params.get("disable_word_count")  # the raw source is known
            assert spec.origin.get("bid") == bid
            assert await _until(scans.entered.is_set, 60), "the QA scan never reached the scanner"
            assert _state(js.snapshot(qa_id)) == "RUNNING"
            assert await _until(lambda: _buttons(book_page)[1] == (True, QA_RUNNING), 10), _buttons(book_page)
