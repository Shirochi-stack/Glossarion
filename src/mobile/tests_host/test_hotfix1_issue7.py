            during = log.during(job_id, mark_log)
            assert during, "no jobs delivery reached the Book page while the translation ran"
            assert all(r["run"][0] and r["qa"][0] for r in during), during
            await _taps_start_nothing(run, book_page, js)
            # leaving the Book page and opening it again: disabled at once
            await run.back()
            assert await _until(lambda: type(app.shell.top_screen).__name__ == "LibraryScreen", 20), run.route()
            log.detach()
            book_page, _bid = await _open_chapters(run, book)
            chapters = book_page.chapters
            assert _state(js.snapshot(job_id)) == "RUNNING" and _settled(server)
            assert _buttons(book_page) == ((True, bp.RUN_WAIT_TRANSLATION), (True, bp.RUN_WAIT_TRANSLATION))
            log.attach(book_page)
            # the run goes on and ends: both come back by themselves
            mark_log, mark_msg = log.mark(), len(run.conn.messages)
            gate.release()
            done = await _wait_end(js, job_id)
            assert _state(done) == "DONE", getattr(done, "error", done)
            assert server.count("translation", since=gate.since) >= CHAPTERS
            assert await _until(lambda: _buttons(book_page) == ((False, None), (False, None)), 20), \
                _buttons(book_page)
            assert app.shell.top_screen is book_page and book_page.chapters is chapters  # still no reopen
            assert all(r["run"][0] and r["qa"][0] for r in log.during(job_id, mark_log)), log.rows[mark_log:]
            after = log.after(job_id, mark_log)
            assert after and not after[-1]["run"][0] and not after[-1]["qa"][0], log.rows[mark_log:]
            assert run.patched_since(mark_msg, chapters.run_button) and run.patched_since(mark_msg, chapters.qa_button)
            assert [s.id for s in js.view().history if _kind(s) == "translate"] == [job_id]  # ONE translation job

            # ---- 3. a glossary-only run (Glossary › Extract glossary): both disabled, back at its end -------
            await driver.tap(text="Glossary", timeout=30)
            await driver.wait(key="gp-extract", timeout=60)
            gate.hold_after("glossary", 0)  # the extraction's first request parks
            mark_log, mark_msg = log.mark(), len(run.conn.messages)
            await driver.tap(key="gp-extract", timeout=10)
            gsnap = await _until(lambda: (s := js.snapshot()) is not None and _kind(s) == "extract_glossary" and s, 60)
            assert gsnap, f"Extract glossary did not run a job: {js.view()}"
            glossary_id = gsnap.id
            assert tuple(_norm(p) for p in gsnap.spec.inputs) == (_norm(raw),)
            assert await _until(lambda: _settled(server), 120), (server.holding, server.parked, server.in_flight(),
                                                                   js.snapshot(glossary_id))
            assert _state(js.snapshot(glossary_id)) == "RUNNING"
            assert server.records("glossary", since=gate.since), "the extraction sent no glossary request"
            await driver.tap(text="Chapters", timeout=30)
            await driver.wait(key="ch-run", timeout=10)
            assert _buttons(book_page) == ((True, bp.RUN_WAIT_GLOSSARY), (True, bp.RUN_WAIT_GLOSSARY))
            assert bp.RUN_WAIT_GLOSSARY.encode() in run.sent_since(mark_msg)  # the reason reached the client
            during = log.during(glossary_id, mark_log)
            assert during and all(r["run"][0] and r["qa"][0] for r in during), during
            await _taps_start_nothing(run, book_page, js)
            gate.release()
