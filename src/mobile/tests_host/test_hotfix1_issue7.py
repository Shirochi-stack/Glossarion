async def _until(predicate, timeout: float = 30.0, interval: float = 0.05):
    deadline = time.monotonic() + timeout
    while True:
        value = predicate()
        if value:
            return value
        if time.monotonic() >= deadline:
            return value
        await asyncio.sleep(interval)


class Run:
    def __init__(self, tf, app, conn, session, page, tester, driver) -> None:
        self.tf, self.app, self.conn, self.session, self.page = tf, app, conn, session, page
        self.tester, self.driver = tester, driver

    def route(self) -> str:
        views = list(self.page.views or [])
        return str(views[-1].route) if views else ""

    async def back(self) -> None:
        views = list(self.page.views or [])
        if len(views) > 1:
            await self.session.dispatch_event(self.page._i, "view_pop", {"route": views[-1].route})

    def on_screen(self, control) -> bool:
        return any(c is control for c in self.tester._walk())

    def sent_since(self, mark: int) -> bytes:
        """Every message sent to the client since ``mark``, msgpack-encoded like the socket transport."""
        import msgpack
        from flet.controls.base_control import BaseControl
        from flet.messaging.protocol import configure_encode_object_for_msgpack

        encode = configure_encode_object_for_msgpack(BaseControl)
        return b"".join(msgpack.packb([m.action, m.body], default=encode) for m in self.conn.messages[mark:])

    def patched_since(self, mark: int, control, prop: str = "disabled") -> bool:
        """A control patch since ``mark`` that changes ``prop`` reached the client for ``control`` (rooted at the
        control itself or at a control of the subtree it is in)."""
        import msgpack
        from flet.controls.base_control import BaseControl
        from flet.messaging.protocol import MessageAction, configure_encode_object_for_msgpack

        encode = configure_encode_object_for_msgpack(BaseControl)
        ids = set()
        node = control
        while node is not None:
            if getattr(node, "_i", None) is not None:
                ids.add(node._i)
            node = getattr(node, "parent", None)
        return any(m.action == MessageAction.PATCH_CONTROL and getattr(m.body, "id", None) in ids
                   and prop.encode() in msgpack.packb(m.body.patch, default=encode)
                   for m in self.conn.messages[mark:])


