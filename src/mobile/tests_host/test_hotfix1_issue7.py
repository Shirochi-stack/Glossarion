class ReplyGate:
    """``HoldGate`` (test_devfix_issue12) for any request kind: ``hold_after(kind, n)`` holds the fake model
    (``server.hold()``: new requests park) once ``n`` replies of ``kind`` went out to requests sent after the
    call - from the server's own ``on_response`` hook; ``n == 0`` holds at once (the job's first request parks).
    ``release()`` lets the parked requests answer; nothing is aborted (an abort makes the client retry)."""

    def __init__(self, server) -> None:
        self.server = server
        self._lock = threading.Lock()
        self.kind = None
        self.since = 0
        self.replies = 0
        self.hold_at = None
        server.on_response.append(self)

    def hold_after(self, kind: str, count: int) -> None:
        with self._lock:
            self.kind = kind
            self.since = self.server.mark()
            self.replies = 0
            self.hold_at = count if count > 0 else None
        if count <= 0:
            self.server.hold()

    def release(self) -> None:
        with self._lock:
            self.hold_at = None
        self.server.release()

    def __call__(self, record) -> None:
        if record.kind != self.kind or record.id <= self.since:
            return
        with self._lock:
            if self.hold_at is None:
                return
            self.replies += 1
            if self.replies < self.hold_at:
                return
            self.hold_at = None
        self.server.hold()


def _settled(server) -> bool:
    """The fake model holds and every request in flight is parked: the job cannot end (test_devfix_issue12)."""
    return server.holding and server.parked >= 1 and server.in_flight() == server.parked


class ScanGate:
    """Wraps ``scan_html_folder.scan_html_folder`` (the real scan still runs) to record what each scan receives;
    ``hold()`` makes the next scan wait at its entry until ``release()`` (a QA scan sends no model request, so
    this is its hold gate)."""

    def __init__(self, monkeypatch) -> None:
        import scan_html_folder as shf

        self.scans: list = []
        self.entered = threading.Event()
        self._open = threading.Event()
        self._open.set()
        self._lock = threading.Lock()
        real = shf.scan_html_folder

        @functools.wraps(real)
        def scan_html_folder(folder_path, log=print, stop_flag=None, mode="quick-scan", qa_settings=None,
                             epub_path=None, **kwargs):
            with self._lock:
                self.scans.append({"folder": _norm(folder_path), "mode": mode, "settings": dict(qa_settings or {}),
                                   "epub": _norm(epub_path) if epub_path else None})
            self.entered.set()
            self._open.wait(JOB_TIMEOUT)
            return real(folder_path, log=log, stop_flag=stop_flag, mode=mode, qa_settings=qa_settings,
                        epub_path=epub_path, **kwargs)

        monkeypatch.setattr(shf, "scan_html_folder", scan_html_folder)

    def hold(self) -> int:
        self.entered.clear()
        self._open.clear()
        return len(self.scans)

    def release(self) -> None:
        self._open.set()


