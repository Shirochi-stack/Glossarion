class ButtonLog:
    """Subscribed to the JobService AFTER the Book page (deliveries run in subscription order), it records, for
    every JobsView, the job(s) and the Book page's Run translation / Run QA scan state right after the page
    handled that view."""

    def __init__(self, job_service) -> None:
        self.js = job_service
        self.rows: list = []
        self.page = None
        self._unsub = None

    def attach(self, book_page) -> None:
        self.detach()
        self.page = book_page
        self._unsub = self.js.subscribe(self._on_view)

    def detach(self) -> None:
        if self._unsub is not None:
            self._unsub()
            self._unsub = None

    def _on_view(self, view) -> None:
        chapters = self.page.chapters
        active = view.active
        self.rows.append({
            "active": (active.id, _kind(active), _state(active)) if active is not None else None,
            "queue": tuple(s.id for s in view.queue),
            "run": (bool(chapters.run_button.disabled), chapters.run_button.tooltip),
            "qa": (bool(chapters.qa_button.disabled), chapters.qa_button.tooltip),
        })

    def mark(self) -> int:
        return len(self.rows)

    def during(self, job_id: str, since: int = 0) -> list:
        return [r for r in self.rows[since:] if (r["active"] and r["active"][0] == job_id) or job_id in r["queue"]]

    def after(self, job_id: str, since: int = 0) -> list:
        rows = self.rows[since:]
        last = max((i for i, r in enumerate(rows) if (r["active"] and r["active"][0] == job_id)
                    or job_id in r["queue"]), default=-1)
        return rows[last + 1:]


