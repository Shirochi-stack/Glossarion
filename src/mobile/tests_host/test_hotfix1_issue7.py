            await asyncio.sleep(0.3)
            new = [s for s in [js.view().active, *js.view().queue, *js.view().history]
                   if s is not None and s.id not in known and _kind(s) == "qa_scan"]
            assert [s.id for s in new] == [qa_id], new  # ONE scan for the double tap and the later tap
            scans.release()
            qdone = await _wait_end(js, qa_id)
            assert _state(qdone) == "DONE", getattr(qdone, "error", qdone)
            # the mobile QA defaults reached the real scanner
            mine = scans.scans[first_scan:]
            assert [s["folder"] for s in mine] == [_norm(workspace)], mine
            assert mine[0]["mode"] == "quick-scan" and mine[0]["settings"].get("quick_scan_sample_size") == 0, mine
            assert mine[0]["epub"] == _norm(raw)
            log_text = Path(js.job_log_path(qa_id)).read_text(encoding="utf-8", errors="replace")
            assert SAMPLE_LINE in log_text, log_text[-2000:]
            assert "QUICK-SCAN mode" in log_text
            report = qa_kind.report_path_for(workspace)
            assert os.path.isfile(report) and any(_norm(p) == _norm(report) for p in qdone.outputs), qdone.outputs
            assert await _until(lambda: _buttons(book_page) == ((False, None), (False, None)), 20), \
                _buttons(book_page)
            assert app.config_store.get(("qa_scanner_settings", "quick_scan_sample_size")) is None  # not written
            # the snackbar offers the report ("Report" is the SnackBar's own action label); its action opens it
