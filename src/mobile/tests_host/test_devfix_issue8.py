def test_owner_issue8_several_library_books_make_one_batch(isolated):
    """Multi-select in the in-chat Library picker: a long-press starts a selection (like the Library's
    own shelves), more taps add books, "Use N" puts them in one BatchPlanCard; its Start runs one
    ``translate`` job over their Library/Raw files (each book's own workspace, the desktop multi-file
    run). A plain tap still attaches one book at once (one tap, test above)."""
    from glossarion_mobile.diagnostics.fake_llm_server import FakeLLMServer

    picks, files = isolated
    tf = _foundations()

    async def scenario(server):
        app, page, tester, driver, books = await _start_with_library(tf, server, picks, files)
        try:
            view = app.chat_view
            chats = app.chat_feature.chats
            js = app.job_service
            cid = await _new_chat(app, page, driver)
            await driver.tap(tooltip=ATTACH)
            await driver.tap(key="attach-library", timeout=10)
            picker = await _open_picker(app, driver)
            beta, gamma = books["Beta Chronicle"], books["Gamma Tales"]
            await tester.long_press(await driver.wait(key=f"book-{beta['bid']}", timeout=10))
            await driver.pump(200)
            assert picker.sheet.open, "a long-press closed the picker"
            assert picker.multi and set(picker.selected) == {t.key for t in picker.rows["library"]
                                                             if t.bid == beta["bid"]}, (
                "a long-press on a Library row does not start a multi-selection in the chat picker")
            await driver.tap(key=f"book-{gamma['bid']}")
            assert len(picker.selected) == 2 and picker.sheet.open
            await driver.wait(text="Use 2", timeout=5)
            await driver.tap(key="picker-done")
            assert await _until(lambda: not picker.sheet.open, 5)
            batch = chats.meta(cid).get("pending_batch") or {}
            assert sorted(_norm(p) for p in batch.get("files") or ()) == sorted(
                _norm(b["raw"]) for b in (beta, gamma)), batch
            await driver.wait(key="batch-start", timeout=30)
            await driver.tap(key="batch-start")
            if await driver.exists(text="Keep translations running", timeout=5):
                await driver.tap(text="Not now")
            snap = await _until(lambda: js.snapshot() or (js.view().history[0] if js.view().history else None), 60)
            assert snap is not None
            assert str(getattr(snap.spec.kind, "value", snap.spec.kind)) == "translate"
            assert sorted(_norm(p) for p in snap.spec.inputs) == sorted(_norm(b["raw"]) for b in (beta, gamma))
            assert snap.spec.origin.get("cid") == cid
            done = await _until(lambda: (s := js.snapshot(snap.id)) is not None and str(
                getattr(s.state, "value", s.state)) in ("DONE", "FAILED", "STOPPED", "CANCELLED") and s, 240)
            assert done and str(getattr(done.state, "value", done.state)) == "DONE", done
            # each book went into its own Library workspace (the desktop multi-file run)
            assert sorted(_norm(d) for d in (done.output_dirs or {}).values()) == sorted(
                _norm(b["workspace"]) for b in (beta, gamma)), done.output_dirs
        except Exception:
            for row in tester.dump(200):
                print(row)
            raise
        finally:
            app.jobs.close()
            await tf._stop(app)

    with FakeLLMServer() as server:
        asyncio.run(scenario(server))
