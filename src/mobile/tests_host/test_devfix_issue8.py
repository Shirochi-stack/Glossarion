async def _host_driver(tf, files: dict):
    from host_tester import HostPicker, PyTester
    from ui_driver import UiDriver

    _m, conn, session, page, app = await tf._start("android")
    picker = HostPicker(files)
    bridge = getattr(app, "files", None)
    if bridge is not None:
        bridge._get_picker = lambda: picker  # what the app's FilePicker service would answer

    async def back():
        views = list(page.views or [])
        if len(views) > 1:
            await session.dispatch_event(page._i, "view_pop", {"route": views[-1].route})

    tester = PyTester(session, page)
    driver = UiDriver(tester, picker=picker, back=back, poll_ms=100, log=lambda *_a: None)
    return app, page, tester, driver


async def _until(predicate, timeout: float = 30.0, interval: float = 0.1):
    deadline = time.monotonic() + timeout
    while True:
        value = predicate()
        if value:
            return value
        if time.monotonic() >= deadline:
            return value
        await asyncio.sleep(interval)


def _route(page) -> str:
    views = list(page.views or [])
    return str(views[-1].route) if views else ""


def _rows(service) -> dict:
    return {str(b.get("folder_name") or b.get("name")): dict(b) for b in service.snapshot.all_books()}


async def _start_with_library(tf, server, picks: Path, files: dict):
    """The app with the fake model imported from a desktop config and the three books imported
    through Library › Import EPUB; workspace mtimes set to ``AGES``. Returns (app, page, tester,
    driver, {stem: {bid, raw, workspace}})."""
    import flows
    from glossarion_mobile.diagnostics.fake_llm_server import FAKE_MODEL

    files = dict(files)
    files[flows.CONFIG_NAME] = flows.write_ui_config(picks / flows.CONFIG_NAME, server.url, FAKE_MODEL)
    app, page, tester, driver = await _host_driver(tf, files)
    await flows.wait_home(driver)
    await flows.import_desktop_config(driver)
    await flows.open_drawer(driver)
    await driver.tap(key="dest-library")
    await driver.wait(key="lib-search", timeout=60)
    for stem, _chapters, _rgb in BOOKS:
        name = f"{stem}.epub"
        await driver.pick_file(name, lambda: driver.tap(key="lib-fab"))  # the In progress shelf's Import EPUB
        await driver.wait(contains=f"Added to Library: {name}", timeout=60)
    service = app.library
    assert await _until(lambda: len(service.snapshot.all_books()) >= 3, 60), _rows(service).keys()
    rows = _rows(service)
    assert set(rows) == {stem for stem, _c, _r in BOOKS}, rows.keys()
    now = time.time()
    for stem, age in AGES.items():
        folder = rows[stem].get("output_folder") or ""
        assert folder and os.path.isdir(folder), rows[stem]  # Import scaffolded the book's workspace
        os.utime(folder, (now - age, now - age))
    service.mark_dirty()
    await service.refresh(reason="devfix8: workspace ages")
    books = {}
    for stem, row in _rows(service).items():
        raw = row.get("raw_source_path") or ""
        assert raw and os.path.isfile(raw) and Path(raw).parent.name == "Raw", row  # copied into Library/Raw
        books[stem] = {"bid": service.bid_for(row), "raw": raw, "workspace": row["output_folder"]}
    await flows.go_home(driver)
    return app, page, tester, driver, books


async def _new_chat(app, page, driver) -> str:
    await driver.tap(tooltip="New chat")
    await driver.wait(key="transcript-empty", timeout=30)
    return app.chat_view.cid


def _newest_first(service, books: dict, stems) -> list:
    """``book-<bid>`` keys of ``stems`` by the Library scan's current mtime, newest first (a run
    touches its workspace, so a book translated in this test moves to the top)."""
    rows = _rows(service)
    ordered = sorted(stems, key=lambda stem: float(rows[stem].get("mtime") or 0.0), reverse=True)
    return [f"book-{books[stem]['bid']}" for stem in ordered]


def _picker_order(picker) -> list:
    """The picker list's book rows top to bottom as ``book-<bid>`` keys."""
    keys = []
    for control in picker.list_view.controls:
        key = _key(control)
        if isinstance(key, str) and key.startswith("pick-") and getattr(control, "controls", None):
            key = _key(control.controls[0])  # an ineligible row: the muted row + its ReasonChip
        keys.append(key)
    return keys


async def _open_picker(app, driver):
    """The chat's Library picker that the last action opened (every earlier one was closed)."""
    view = app.chat_view

    def opened():
        picker = view.library_picker
        return picker if picker is not None and picker.sheet.open else None

    picker = await _until(opened, 15)
    assert picker is not None, "no in-chat Library picker opened"
    assert await _until(lambda: picker.loaded, 30), "the picker never loaded its rows"
    await driver.wait(key="picker-title", timeout=10)
    return picker


async def _send_text(driver, text: str) -> None:
    await driver.enter(text, text=COMPOSER_HINT)
    await driver.tap(key="send-idle_ready", timeout=10)


