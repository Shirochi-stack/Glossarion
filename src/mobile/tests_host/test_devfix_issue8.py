def _epub(path: Path, title: str, chapters: int, rgb: tuple) -> Path:
    """A small Korean EPUB with its own identifier and a PNG cover (the picker shows covers)."""
    from ebooklib import epub

    from glossarion_mobile.diagnostics.fake_llm_server import png_bytes

    book = epub.EpubBook()
    book.set_identifier(f"glossarion-devfix8-{title.lower().replace(' ', '-')}")
    book.set_title(title)
    book.set_language("ko")
    book.add_author("Glossarion")
    book.set_cover("cover.png", png_bytes(60, 90, rgb))
    items = []
    for index in range(1, chapters + 1):
        chapter = epub.EpubHtml(title=f"제{index}장", file_name=f"chapter{index:04d}.xhtml", lang="ko")
        chapter.content = (f"<html><head><title>제{index}장</title></head><body><h1>제{index}장</h1>"
                           f"<p>{title} 이야기의 {index}번째 장입니다. 주인공은 길을 떠났다.</p></body></html>")
        book.add_item(chapter)
        items.append(chapter)
    book.toc = tuple(items)
    book.add_item(epub.EpubNcx())
    book.add_item(epub.EpubNav())
    book.spine = ["nav", *items]
    path.parent.mkdir(parents=True, exist_ok=True)
    epub.write_epub(str(path), book)
    return path


